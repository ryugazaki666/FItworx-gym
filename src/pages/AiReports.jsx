import { useState, useRef, useEffect } from "react";
import { Sparkles, Send, ChevronDown, ChevronUp, Database } from "lucide-react";
import { api } from "../lib/api";

const EXAMPLES = [
  "How many active members do we have right now?",
  "Which members are expiring within 7 days?",
  "What was our total revenue this month?",
  "How many walk-in customers visited today and how much revenue did they bring in?",
  "Who are our five most frequent visitors this week?",
  "List pending payments.",
];

export default function AiReports() {
  const [question, setQuestion] = useState("");
  const [thread, setThread] = useState([]);
  const [loading, setLoading] = useState(false);
  const bottomRef = useRef(null);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [thread]);

  async function ask(q) {
    const text = (q ?? question).trim();
    if (!text || loading) return;
    setQuestion("");
    setThread((t) => [...t, { role: "user", text }]);
    setLoading(true);
    try {
      const result = await api.post("/ai/query", { question: text });
      setThread((t) => [...t, { role: "assistant", text: result.answer, toolTrace: result.toolTrace }]);
    } catch (err) {
      setThread((t) => [...t, { role: "error", text: err.message }]);
    } finally {
      setLoading(false);
    }
  }

  return (
    <div>
      <div className="mb-6">
        <h1 className="text-2xl font-bold flex items-center gap-2"><Sparkles size={22} className="text-blue-600" /> AI Reporting Assistant</h1>
        <p className="text-ink-500 text-sm mt-1.5 max-w-[720px]">
          Ask about members, walk-ins, payments, revenue, or attendance in plain language. Every answer is generated by
          querying the actual FitWorx database — the assistant cannot invent figures or records.
        </p>
      </div>

      <div className="card card-pad mb-5">
        <div className="text-[12.8px] font-semibold text-ink-700 mb-2.5">Try asking</div>
        <div className="flex flex-wrap gap-2">
          {EXAMPLES.map((ex) => (
            <button key={ex} className="btn btn-secondary btn-sm" onClick={() => ask(ex)} disabled={loading}>
              {ex}
            </button>
          ))}
        </div>
      </div>

      <div className="card card-pad">
        <div className="flex flex-col gap-4 max-h-[520px] overflow-y-auto pr-1">
          {thread.length === 0 && (
            <div className="text-ink-400 text-[13.5px] text-center py-10">
              Ask a question above or type one below to get started.
            </div>
          )}
          {thread.map((msg, i) => (
            <ThreadMessage key={i} msg={msg} />
          ))}
          <div ref={bottomRef} />
          {loading && (
            <div className="flex items-center gap-2 text-ink-400 text-[13px]">
              <Sparkles size={14} className="animate-pulse" /> Looking up the data…
            </div>
          )}
        </div>

        <div className="flex items-center gap-2.5 mt-5 pt-4 border-t border-line-soft">
          <input
            className="input flex-1"
            placeholder="e.g. How much revenue did we make from walk-ins this week?"
            value={question}
            onChange={(e) => setQuestion(e.target.value)}
            onKeyDown={(e) => e.key === "Enter" && ask()}
            disabled={loading}
          />
          <button className="btn btn-accent btn-sm" onClick={() => ask()} disabled={loading || !question.trim()}>
            <Send size={15} /> Ask
          </button>
        </div>
      </div>
    </div>
  );
}

function ThreadMessage({ msg }) {
  const [showData, setShowData] = useState(false);

  if (msg.role === "user") {
    return (
      <div className="flex justify-end">
        <div className="bg-blue-600 text-white rounded-2xl rounded-br-sm px-4 py-2.5 max-w-[80%] text-[13.8px]">
          {msg.text}
        </div>
      </div>
    );
  }

  if (msg.role === "error") {
    return (
      <div className="flex justify-start">
        <div className="bg-red-100 border border-red-200 text-red-700 rounded-2xl rounded-bl-sm px-4 py-2.5 max-w-[85%] text-[13.5px]">
          {msg.text}
        </div>
      </div>
    );
  }

  return (
    <div className="flex justify-start">
      <div className="bg-surface border border-line rounded-2xl rounded-bl-sm px-4 py-3 max-w-[85%]">
        <div className="text-[13.8px] text-ink-900 whitespace-pre-wrap leading-relaxed">{msg.text}</div>
        {msg.toolTrace && msg.toolTrace.length > 0 && (
          <div className="mt-2.5 pt-2.5 border-t border-line-soft">
            <button
              className="flex items-center gap-1.5 text-[11.5px] font-semibold text-ink-500 hover:text-ink-700"
              onClick={() => setShowData((s) => !s)}
            >
              <Database size={12} /> {showData ? "Hide" : "Show"} data used ({msg.toolTrace.length} lookup{msg.toolTrace.length > 1 ? "s" : ""})
              {showData ? <ChevronUp size={12} /> : <ChevronDown size={12} />}
            </button>
            {showData && (
              <div className="mt-2 flex flex-col gap-2">
                {msg.toolTrace.map((t, i) => (
                  <div key={i} className="bg-white rounded-lg border border-line-soft p-2.5">
                    <div className="text-[11px] font-bold text-blue-600 uppercase tracking-wide">{t.tool}</div>
                    <pre className="text-[10.8px] text-ink-500 mt-1 whitespace-pre-wrap break-words">{JSON.stringify(t.result, null, 2)}</pre>
                  </div>
                ))}
              </div>
            )}
          </div>
        )}
      </div>
    </div>
  );
}
